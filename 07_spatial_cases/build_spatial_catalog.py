def build():
    rows = []
    for (i, stage, grade, subject, name, book, skel, oper, model, judge, tech, prio, prompt, note) in ROWS:
        rows.append({
            "ID": i, "学段": stage, "年级": grade, "学科": subject, "案例": name,
            "教材位置": book, "骨架": skel, "骨架名": SKEL[skel][0],
            "可操作": oper, "核心模型": model, "审查判据": judge,
            "技术方案": tech, "技术说明": TECH[tech][0], "优先级": prio,
            "输入句": prompt, "备注": note,
            "状态": "待做",
        })
    return rows


def write_json(rows):
    doc = {
        "说明": "空间与过程类教学工具需求清单。字段与 06_full_catalog 对齐，可合并进主清单。",
        "骨架定义": {k: {"名称": v[0], "含义": v[1], "审查方式": v[2]} for k, v in SKEL.items()},
        "技术方案": {k: {"名称": v[0], "适用": v[1]} for k, v in TECH.items()},
        "总计": len(rows),
        "案例": rows,
    }
    path = os.path.join(BASE, "spatial_cases.json")
    with io.open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    return path


