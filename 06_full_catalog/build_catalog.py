def md_table(items):
    head = ("| ID | 年级 | 案例 | 形态 | 可调参数 | 核心模型 | 可视化 | 审查判据 | 优先级 | 状态 |\n"
            "|---|---|---|---|---|---|---|---|---|---|\n")
    lines = []
    for d in items:
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            d["ID"], d["年级"], d["案例"], d["形态"], d["可调参数"],
            d["核心模型"], d["可视化"], d["审查判据"], d["优先级"], d["状态"]))
    return head + "\n".join(lines)


