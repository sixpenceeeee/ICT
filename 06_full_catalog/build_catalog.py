def write_csv(rows):
    path = os.path.join(BASE, "全学段案例清单.csv")
    cols = FIELDS + ["建议文件名"]
    with io.open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for d in rows:
            w.writerow({k: d[k] for k in cols})
    return path


