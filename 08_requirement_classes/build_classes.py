def stats():
    total = sum(c["估算"][0] for c in CLASSES), sum(c["估算"][1] for c in CLASSES)
    per_family = {}
    for f in FAMILIES:
        items = [c for c in CLASSES if c["族"] == f["id"]]
        per_family[f["id"]] = (len(items), sum(c["现有"] for c in items),
                               sum(c["估算"][0] for c in items), sum(c["估算"][1] for c in items))
    return total, per_family


