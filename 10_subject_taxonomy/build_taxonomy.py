def load_cases():
    """读入 06 与 07 两份清单，统一成 {学科, 案例} 结构。"""
    out = []
    p6 = os.path.join(ROOT, "06_full_catalog", "全学段案例清单.json")
    if os.path.exists(p6):
        with io.open(p6, encoding="utf-8") as f:
            for r in json.load(f)["案例"]:
                out.append({"ID": r["ID"], "学科": r["学科"], "案例": r["案例"],
                            "状态": r["状态"]})
    p7 = os.path.join(ROOT, "07_spatial_cases", "spatial_cases.json")
    if os.path.exists(p7):
        with io.open(p7, encoding="utf-8") as f:
            for r in json.load(f)["案例"]:
                out.append({"ID": r["ID"], "学科": r["学科"], "案例": r["案例"],
                            "状态": "未做"})
    return out


def assign(cases):
    """把每条案例归到某类需求。返回 (类型编号 -> [案例名], 未归类列表)。"""
    by_code = {}
    unmapped = []
    for c in cases:
        abbr = {"数学": "MA", "物理": "PH", "化学": "CH", "生物": "BI",
                "地理": "GE", "信息科技": "CS"}.get(c["学科"])
        if not abbr:
            unmapped.append(c)
            continue
        hit = None
        for kws, code in RULES.get(abbr, []):
            if any(k in c["案例"] for k in kws):
                hit = code
                break
        if hit:
            by_code.setdefault(hit, []).append(c["案例"])
        else:
            unmapped.append(c)
    # 两份清单里可能有同名案例（如 06 的旧版与 07 的升级版），显示时去重
    for k, v in by_code.items():
        by_code[k] = list(dict.fromkeys(v))
    return by_code, unmapped


def build():
    cases = load_cases()
    by_code, unmapped = assign(cases)
    stats = {"案例总数": len(cases), "已归类": len(cases) - len(unmapped),
             "未归类": len(unmapped),
             "去重后": sum(len(v) for v in by_code.values())}

    subj_rows, type_rows = [], []
    for s in SUBJECTS:
        n_existing = 0
        for t in s["类型"]:
            code, name, what, examples, judge, prio, note = t
            got = by_code.get(code, [])
            n_existing += len(got)
            type_rows.append({
                "编号": code, "学科": s["学科"], "学段": s["学段"], "需求类型": name,
                "内容形态": FORM.get(code, "未标注"),
                "页面做什么": what, "典型内容": examples,
                "判据编号": judge, "判据名称": JUDGE[judge][0],
                "现有案例数": len(got),
                "现有案例": "、".join(got),
                "现有案例列表": got,
                "优先级": prio, "备注": note,
            })
        subj_rows.append({
            "学科": s["学科"], "学段": s["学段"],
            "定位": s["定位"],
            "类数": len(s["类型"]),
            "类型清单": " / ".join(t[1] for t in s["类型"]),
            "现有案例数": n_existing,
        })

    return subj_rows, type_rows, stats, unmapped


def write_csv(rows):
    cols = ["编号", "学科", "学段", "需求类型", "内容形态", "页面做什么", "典型内容",
            "判据编号", "判据名称", "现有案例数", "现有案例", "优先级", "备注"]
    p = os.path.join(BASE, "学科需求分类.csv")
    with io.open(p, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({k: r[k] for k in cols})
    return p


def write_json(subj_rows, rows, stats, unmapped):
    p = os.path.join(BASE, "学科需求分类.json")
    doc = {
        "说明": "按学科组织的需求类型分类。判据 J1~J8 是跨学科复用的审查单元。",
        "统计": {
            "学科数": len(subj_rows),
            "需求类型数": len(rows),
            "案例总数": stats["案例总数"],
            "已归类": stats["已归类"],
            "未归类": stats["未归类"],
            "按判据": {k: sum(1 for r in rows if r["判据编号"] == k)
                        for k in JUDGE},
            "按优先级": {k: sum(1 for r in rows if r["优先级"] == k)
                          for k in ("P0", "P1", "P2", "不做")},
        },
        "判据": [{"编号": k, "名称": v[0], "怎么验": v[1]} for k, v in JUDGE.items()],
        "学科": subj_rows,
        "需求类型": rows,
        "未归类案例": [{"ID": c["ID"], "学科": c["学科"], "案例": c["案例"]}
                        for c in unmapped],
    }
    with io.open(p, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
    return p, doc


